// Contract check (real-client contract section 4). Each golden in the server's testdata is a JSON file:
//   {"type":"Summary","method":"GET","path":"/api/v2/summary","status":200,"body":{...}}
// `type` names an exported type in types.ts or flowTypes.ts (a trailing [] is allowed). The script writes one temporary
// .ts file that annotates each body with its type, runs tsc over the project, and removes the file. Object-literal
// checks catch extra keys, missing keys and wrong value types. No goldens means nothing to check: exit 0.
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";

const dir = resolve(process.argv[2] ?? "../internal/api/testdata/contract");
const generated = resolve("src/api/contract.generated.ts");

if (!existsSync(dir)) {
  console.log(`contract: no goldens in ${dir}; nothing to check`);
  process.exit(0);
}
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
if (files.length === 0) {
  console.log(`contract: no goldens in ${dir}; nothing to check`);
  process.exit(0);
}

const names = (file) => new Set([...readFileSync(file, "utf8").matchAll(/export (?:interface|type) (\w+)/g)].map((m) => m[1]));
const typesNames = names("src/api/types.ts");
const flowNames = names("src/api/flowTypes.ts");

const body = [];
const used = new Set();
const problems = [];
files.forEach((f, i) => {
  let golden;
  try {
    golden = JSON.parse(readFileSync(join(dir, f), "utf8"));
  } catch (e) {
    problems.push(`${f}: not JSON (${e.message})`);
    return;
  }
  // A status-only golden ("none", e.g. 204 from sign-out): the body must be null, and there is no type to check.
  if (golden.type === "none") {
    if (golden.body !== null) problems.push(`${f}: type "none" needs a null body`);
    return;
  }
  const base = String(golden.type ?? "").replace(/\[\]$/, "");
  const suffix = String(golden.type ?? "").slice(base.length);
  // A built-in primitive (the sources list is a string array): checked as it is, with no type to import.
  if (["string", "number", "boolean"].includes(base)) {
    body.push(`export const c${i}: ${base}${suffix} = ${JSON.stringify(golden.body, null, 2)};`);
    return;
  }
  const ns = typesNames.has(base) ? "T" : flowNames.has(base) ? "F" : null;
  if (!ns) {
    problems.push(`${f}: type "${golden.type}" is not exported from types.ts or flowTypes.ts`);
    return;
  }
  used.add(ns);
  body.push(`export const c${i}: ${ns}.${base}${suffix} = ${JSON.stringify(golden.body, null, 2)};`);
});
if (problems.length) {
  console.error("contract: " + problems.join("\n"));
  process.exit(1);
}

// Only the namespaces in use are imported (an unused import fails tsc under noUnusedLocals).
const imports = [];
if (used.has("T")) imports.push('import type * as T from "./types.ts";');
if (used.has("F")) imports.push('import type * as F from "./flowTypes.ts";');
if (body.length === 0) {
  console.log(`contract: ${files.length} status-only golden(s) in ${dir} match`);
  process.exit(0);
}
writeFileSync(generated, ["// Generated by scripts/contract.mjs. Removed after the check.", ...imports, ...body].join("\n") + "\n");
let status = 0;
try {
  const r = spawnSync("npx", ["tsc", "--noEmit", "-p", "tsconfig.json"], { encoding: "utf8" });
  if (r.status !== 0) {
    console.error(`contract: ${files.length} golden(s) in ${dir} do not match types.ts:\n${r.stdout}${r.stderr}`);
    status = 1;
  } else {
    console.log(`contract: ${files.length} golden(s) in ${dir} match types.ts`);
  }
} finally {
  rmSync(generated, { force: true });
}
process.exitCode = status;
